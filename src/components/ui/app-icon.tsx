export function AppIcon({
  name,
  size = 15,
  spin,
  className,
  style,
}: {
  name: string;
  size?: number;
  spin?: boolean;
  className?: string;
  style?: CSSProperties;
}) {
  const Icon = ICON_MAP[name] ?? File;
  const filled = name === "star-full" ? "currentColor" : "none";
  const classes = ["app-icon shrink-0", spin ? "animate-spin" : "", className ?? ""].filter(Boolean).join(" ");
  return (
    <Icon
      aria-hidden
      size={size}
      strokeWidth={1.65}
      fill={filled}
      className={classes}
      style={style}
    />
  );
}

