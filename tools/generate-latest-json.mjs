#!/usr/bin/env node
/**
 * 生成 tauri-plugin-updater 使用的 latest.json 更新清单（M7 任务 12、M8 任务 06）。
 *
 * Tauri updater 请求配置的 endpoint，按 Static Format 读取：
 *   { version, notes, pub_date, platforms: {
 *       "darwin-aarch64": { url, signature },
 *       "windows-x86_64": { url, signature } } }
 * signature 原样使用 Tauri 生成的 .sig 内容（已编码的 minisign 签名）。
 * 插件只解码一次；不能再次编码 .sig。
 *
 * 输入：
 *   --artifacts <dir>           收集好的 macOS 产物（.app.tar.gz 与 .app.tar.gz.sig）
 *   --windows-artifacts <dir>   Windows 产物目录（*-setup.exe 与同名 .sig；
 *                               v1Compatible 模式也接受 *.nsis.zip）
 *   --require-windows           缺少 Windows 安装包或签名时失败（发布构建使用）
 *   --download-base <url>       产物在 Release 里的下载地址前缀（https）
 *   --version <v>               应用版本（不带 v 前缀）
 *   --notes <file|->            Release notes 文本或路径（可选）
 * 输出：stdout 打印 latest.json 内容；由 CI 写入文件并上传到 Release。
 */
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

function arg(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const artifactsDir = arg("artifacts");
const windowsDir = arg("windows-artifacts");
const requireWindows = process.argv.includes("--require-windows");
const downloadBase = (arg("download-base") ?? "").replace(/\/$/, "");
const version = arg("version") ?? "";

if (!artifactsDir || !version) fail("--artifacts and --version are required");
if (!downloadBase.startsWith("https://")) fail("--download-base must be an https URL");

const files = readdirSync(artifactsDir);
const updaterPackage = files.find((name) => name.endsWith(".app.tar.gz") && !name.endsWith(".sig"));
const signatureFile = updaterPackage && files.find((name) => name === `${updaterPackage}.sig`);
if (!updaterPackage || !signatureFile) {
  fail("artifacts directory must contain *.app.tar.gz and its .sig");
}

const platforms = {
  // Tauri macOS Apple Silicon 的 updater target（wry/tauri 约定 os-arch）。
  "darwin-aarch64": {
    // GitHub Release 资产的下载地址；名称必须与上传产物一致。
    signature: readSignature(join(artifactsDir, signatureFile), "macOS"),
    url: `${downloadBase}/${encodeURIComponent(updaterPackage)}`,
  },
};

const windows = windowsArtifacts(windowsDir);
if (windows) {
  platforms["windows-x86_64"] = {
    signature: readSignature(windows.signature, "Windows"),
    url: `${downloadBase}/${encodeURIComponent(windows.package)}`,
  };
} else if (requireWindows) {
  fail("Windows NSIS updater package and signature are required");
}

const notesArg = arg("notes");
const notes = notesArg && notesArg !== "-" ? readFileSync(notesArg, "utf8") : null;

const manifest = {
  version,
  notes,
  pub_date: new Date().toISOString(),
  platforms,
};

process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);

function windowsArtifacts(directory) {
  if (!directory) return null;
  let files;
  try {
    files = readdirSync(directory);
  } catch {
    fail(`windows artifacts directory does not exist: ${directory}`);
  }
  // Tauri v2 的 createUpdaterArtifacts=true 以 NSIS setup.exe 本身作为更新包；
  // v1Compatible 模式才会额外生成 .nsis.zip。
  const packageName =
    files.find((name) => name.endsWith("-setup.exe") && files.includes(`${name}.sig`)) ??
    files.find((name) => name.endsWith(".nsis.zip") && files.includes(`${name}.sig`));
  if (!packageName) return null;
  if (!packageName.includes(version)) {
    fail(`Windows updater package ${packageName} does not contain version ${version}`);
  }
  return { package: packageName, signature: join(directory, `${packageName}.sig`) };
}

function readSignature(path, platform) {
  const signatureText = readFileSync(path, "utf8").trim();
  const decoded = Buffer.from(signatureText, "base64");
  if (
    decoded.toString("base64") !== signatureText ||
    !decoded.toString("utf8").startsWith("untrusted comment:")
  ) {
    fail(`${platform} signature file must contain the base64 signature generated by Tauri`);
  }
  return signatureText;
}

function fail(message) {
  console.error(`latest-json: ${message}`);
  process.exit(1);
}
